#define MAX_LED 5
#define USE_BRIGHTNESS 1

int datasentflag =0;

uint8_t LED_Data[MAX_LED][4];
uint8_t LED_Mod[MAX_LED][4]; //for brightness

void HAL_TIM_PWM_PulseFinishedCallback(TIM_HandleTypeDef *htim)
{
	HAL_TIMEx_PWMN_Stop_DMA(&htim1, TIM_CHANNEL_1);
	datasentflag =1;
}


#define PI 3.14159265

void Set_Brightness(int brightness)
{
#if USE_BRIGHTNESS
	if(brightness>45) brightness = 45;
	for(int i=0;i<MAX_LED;i++)
	{
		LED_Mod[i][0] = LED_Data[i][0];
		for(int j=1;j<4;j++)
		{
			float angle = 90- brightness;
			angle = angle*PI/180;
			LED_Mod[i][j] = (LED_Data[i][j])/(tan(angle));
		}
	}
#endif
}
void Set_LED(int LEDnum, int Red, int Green, int Blue)
{
	LED_Data[LEDnum][0]= LEDnum;
	LED_Data[LEDnum][1]= Green;
	LED_Data[LEDnum][2]= Red;
	LED_Data[LEDnum][3]= Blue;

}
uint16_t pwmData[(24*MAX_LED)+50];
void send(int Green , int Red, int Blue)
{
	uint32_t data = (Green<<16) | (Red<<8)| Blue;
	for(int i=23;i>=0;i--)
	{
		if(data&(1<<i))	pwmData[i] =150;
		else	pwmData[i] = 75;
	}
	HAL_TIM_PWM_Start_DMA(&htim1, TIM_CHANNEL_1, (uint32_t *)pwmData, 24);
}

void WS2812B_Send(void)
{
	uint32_t indx =0;
	uint32_t color;
	for(int i=0;i< MAX_LED;i++)
	{
		color = ((LED_Mod[i][1]<<16) |(LED_Mod[i][2]<<8) | (LED_Mod[i][3]));
		for(int i=23;i>=0;i--)
		{
				if(color&(1<<i))
				{
					pwmData[indx] =150;
				}
				else pwmData[indx] = 75;
				indx++;

		}
	}
	for(int i=0;i<50;i++)
	{
		pwmData[indx] =0;
		indx++;
	}
	HAL_TIM_PWM_Start_DMA(&htim1, TIM_CHANNEL_1, (uint32_t *)pwmData, indx);
	while(!datasentflag){};
	datasentflag =0;
}
