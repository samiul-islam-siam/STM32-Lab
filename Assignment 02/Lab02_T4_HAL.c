static void PWM_SetDuty(uint8_t pct)
{
    if (pct > 100U) pct = 100U;
    uint32_t arr  = __HAL_TIM_GET_AUTORELOAD(&htim3);   /* 999 */
    uint32_t ccr1 = (uint32_t)pct * (arr + 1U) / 100U;
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, ccr1);
}

