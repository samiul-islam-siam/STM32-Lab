/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  char buf[100];
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM2_Init();
  MX_TIM6_Init();
  MX_USART2_UART_Init();

  /* USER CODE BEGIN 2 */

  /* Start TIM6 for delay_ms() */
  HAL_TIM_Base_Start(&htim6);

  /* Start PWM on TIM2 CH1 (PA0) */
  HAL_TIM_PWM_Start(&htim2, TIM_CHANNEL_1);

  /*
   * MG996R Servo:
   * 50 Hz PWM (20 ms)
   *
   * 0°   -> 0.5 ms pulse -> CCR = 450
   * 90°  -> 1.5 ms pulse -> CCR = 1350
   * 180° -> 2.5 ms pulse -> CCR = 2250
   */

  HAL_UART_Transmit(&huart2,
      (uint8_t*)"\r\n===== Task 6B: Servo Motor Control (HAL) =====\r\n",
      55,
      HAL_MAX_DELAY);

  HAL_UART_Transmit(&huart2,
      (uint8_t*)"Angle | Pulse (us) | CCR\r\n",
      28,
      HAL_MAX_DELAY);

  HAL_UART_Transmit(&huart2,
      (uint8_t*)"------+------------+-----\r\n",
      28,
      HAL_MAX_DELAY);

  delay_ms(1000U);

  /* Sweep from 0° to 180° */
  for (uint8_t angle = 0; angle <= 180U; angle += 10U)
  {
      float t_us = 500.0f + ((float)angle / 180.0f) * 2000.0f;

      /* Timer tick = 900 kHz -> 1 tick = 1.111 us
       * CCR = t_us × 0.9
       */
      uint32_t ccr = (uint32_t)(t_us * 0.9f);

      __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, ccr);

      snprintf(buf, sizeof(buf),
          "%5u | %10.2f | %4lu\r\n",
          angle,
          t_us,
          (unsigned long)ccr);

      HAL_UART_Transmit(&huart2,
          (uint8_t*)buf,
          strlen(buf),
          HAL_MAX_DELAY);

      delay_ms(500U);
  }

  /* Return to center position */
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, 1350);

  HAL_UART_Transmit(&huart2,
      (uint8_t*)"\r\nParked at 90 degrees.\r\n",
      30,
      HAL_MAX_DELAY);

  HAL_UART_Transmit(&huart2,
      (uint8_t*)"===== Task 6B Complete =====\r\n",
      34,
      HAL_MAX_DELAY);

  /* USER CODE END 2 */

  /* Infinite loop */

  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

